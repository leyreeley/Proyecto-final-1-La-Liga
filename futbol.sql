-- Crear la base de datos y usarla
DROP DATABASE IF EXISTS futbol;
CREATE DATABASE IF NOT EXISTS futbol;
USE futbol;

-- 1. Tabla Ciudades
CREATE TABLE IF NOT EXISTS Ciudades (
    id_ciudad INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

-- 2. Tabla Estadios
CREATE TABLE IF NOT EXISTS Estadios (
    id_estadio INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    capacidad INT NOT NULL,
    id_ciudad INT,
    FOREIGN KEY (id_ciudad) REFERENCES Ciudades(id_ciudad)
);

-- 3. Tabla Equipos
CREATE TABLE IF NOT EXISTS Equipos (
    id_equipo INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    anio_fundacion VARCHAR(4) NOT NULL,
    id_estadio INT,
    FOREIGN KEY (id_estadio) REFERENCES Estadios(id_estadio)
);

-- 4. Tabla Jugadores
CREATE TABLE IF NOT EXISTS Jugadores (
    id_jugador INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    posicion VARCHAR(50) NOT NULL,
    dorsal INT NOT NULL,
    nacionalidad VARCHAR(150) NOT NULL,
    id_equipo INT,
    FOREIGN KEY (id_equipo) REFERENCES Equipos(id_equipo)
);

-- 5. Tabla Estadisticas
CREATE TABLE IF NOT EXISTS Estadisticas (
    id_estadistica INT AUTO_INCREMENT PRIMARY KEY,
    id_jugador INT UNIQUE, -- El UNIQUE garantiza que un jugador solo tenga un registro de estadísticas
    goles INT DEFAULT 0,
    asistencias INT DEFAULT 0,
    tarjetas_amarillas INT DEFAULT 0,
    tarjetas_rojas INT DEFAULT 0,
    partidos_titular INT DEFAULT 0,
    partidos_suplente INT DEFAULT 0,
    partidos_sin_jugar INT DEFAULT 0,
    FOREIGN KEY (id_jugador) REFERENCES Jugadores(id_jugador)
);

